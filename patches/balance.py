from tools.d2patch import patch

# 地狱元素抗性封顶 100：原版有 110/120 这类"绝对免疫"，降抗/无限也破不掉，
# 单元素 build 在这些怪面前完全无解。封顶到 100 后至少能被降抗撕开一个口子。
for col in ("ResFi(H)", "ResLi(H)", "ResCo(H)", "ResPo(H)"):
    patch("monstats.txt", why="地狱抗性封顶 100，消灭绝对免疫", soft=True).all().clamp(col, hi=100)
