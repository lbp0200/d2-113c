"""P3 · 轻度平衡修补。

原则：**外科手术，不动整体曲线**。轻度修补的意义是「把明显不该存在的东西去掉」，
不是重做游戏。每加一条都要问：这条改动会不会让玩家重新学一遍这个职业？

清单（详见 PLAN.md §5）：地狱绝对免疫 / A3 铁狼与 A5 野蛮人佣兵 / 废技能 / 过渡期装备。

---

## 数据依据（`docs/p1-immunity.md`，735 个怪物条目，vanilla 1.13c）

| 元素 | 地狱免疫(>=100) | 其中 >100（连降抗也难破） | 其中 >=1000（设计上绝对免疫） |
|---|---:|---:|---:|
| 火 | 113 | 89 | 0 |
| 冰 | 137 | 125 | 1 |
| 电 | 105 | 33 | 0 |
| 毒 | 131 | 102 | 16 |
| 物理 | 20 | 0 | 0 |
| 魔法 | 11 | 1 | 0 |

「>100」才是真问题：抗性 R 要降到 100 以下需要 `-res >= R-100`，而对免疫怪降抗只按 **1/5**
生效，所以实际需要 `5*(R-100)` 点降抗。最极端的例子：

- **崔凡克 `cantor3` 冰抗 160** → 需要 300 点降抗。纯冰法在崔凡克（符文主要farm点）**完全无解**。
- `Act 5 - Ice Cave 2` 三种怪冰抗 135~160，全部打不穿。
- 纯电 build 的死角：`Act 1 - Graveyard / Crypt 1 A / Crypt 2 A / Cave 2 / Act 2 - Tomb 1 A`。

## 本补丁做什么

把抗性 **封顶到 100**：
- 免疫怪的数量 **一个都不减少**（还是打不动），所以没有降低难度；
- 但任何 `-res` 手段（降抗诅咒 / 信念 / 装备）都能生效，单元素 build 有了解法。
- 排除 `>=1000` 的设计性绝对免疫（那些不是「不合理」，是故意的）。
"""

from tools.d2patch import lt, patch

for col in ("ResFi(H)", "ResLi(H)", "ResCo(H)", "ResPo(H)"):
    patch(
        "monstats.txt",
        why="地狱抗性封顶 100：免疫数量不变，但任何降抗都能生效（排除 1000 的设计性绝对免疫）",
        soft=True,
    ).where(col, lt(1000)).clamp(col, hi=100)
