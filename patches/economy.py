"""L1 · 收益挂钩挑战：资源分工（只动地狱档）。

## 已定参数（2025-11）

- **P1 毕业时间：不变** → 不提高符文总产出，只做"再分配"
- **P2 是否提难度：不提** → 不动 `monlvl` / `difficultylevels`
- **P3 允许加法** → 后续可以用新增 TC 行 / cube 配方做补偿

## 数据说明（`docs/p1-economy.md`）

按 `/players 8`、每小时触发的 Good 判定次数：

| 路线 | Good/事件 | 事件/小时 | Good/小时 | 需要战斗 |
|---|---:|---:|---:|---|
| LK 超级箱子 | 14.81% | 1440 | **213** | ❌ |
| 崔凡克 | 23.68% | 1080 | **256** | ✅ |
| 牛场 | 4.17% | 3000 | 125 | ✅ |
| 白怪清场 | 2.78% | 3000 | 83 | ✅ |
| 暗金怪 | 6.45% | 48 | 3 | ✅ |
| 精英怪 | 1.50% | 96 | 1 | ✅ |

**关键结论：精英/暗金在数学上不可能成为符文主来源。**
它们每小时只有几十次事件，而白怪/箱子是几千次。要让 48 次/小时追上 83 次/小时，
单次概率得超过 170%——不存在。所以"让打精英怪变值钱"这条路走不通，
真正该砍的只有**零战斗的高频源**。

## 所以改动只有一条主线 + 一条点缀

1. **地狱箱子不再产符文**（`Good` 权重清零，权重自动让给金币/装备/Junk）。
   箱子继续是补给源（宝石/装备/金币），但拿不到构筑核心。
   - 只动地狱（`(H)`）：普通/噩梦靠箱子过渡是合理的，不动。
2. **精英/暗金小幅提升**（`Citem` 3→6、`Uitem` 4→8）：让"打硬目标"有额外意义，
   但它不是主来源，别指望靠它刷符文。
3. **白怪 / 牛场 / 崔凡克一律不动**：它们本来就是战斗来源，符合 S2。

## 为什么这不是"惩罚玩法"

上一版讨论里我反对孤立地削 LK。这里的区别是：**砍掉箱子之后，符文路径全部落在战斗上**，
而战斗路径的产出（83~256）本来就够用，玩家不需要"补偿"。
P1 说总量不变，正好对上——玩家会从 LK 转向牛场/崔凡克，产出量级持平。

## 未做

- 不动崔凡克：它是战斗源，且对冰系免疫（`cantor3` 冰抗 160）→ **build 参与决策**，
  正是 S2 想要的样子。虽然它也是"高频定点"，但它需要能打的角色。
"""

from tools.d2patch import matches, patch

# 1. 地狱箱子不再产符文
patch(
    "treasureclassex.txt",
    why="L1 地狱箱子不再产符文：符文路径全部落到战斗源上",
).where(
    "Treasure Class", matches(r"^Act \d \(H\) Chest [ABC]$")
).item_prob(r"Good$", 0, label="Prob(Good)")

# 2. 精英怪：Good 权重 3 → 6（点缀，不是主来源）
patch(
    "treasureclassex.txt",
    why="L1 精英怪 Good 权重 3→6（打硬目标的额外回报）",
).where(
    "Treasure Class", matches(r"^Act \d \(H\) Citem [ABC]$")
).item_prob(r"Good$", 6, label="Prob(Good)")

# 3. 暗金怪：Good 权重 4 → 8
patch(
    "treasureclassex.txt",
    why="L1 暗金怪 Good 权重 4→8（打硬目标的额外回报）",
).where(
    "Treasure Class", matches(r"^Act \d \(H\) Uitem [ABC]$")
).item_prob(r"Good$", 8, label="Prob(Good)")
