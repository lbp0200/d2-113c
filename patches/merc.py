"""B 档 · 雇佣兵：只修 A3 铁狼与 A5 野蛮人的"贵 + 脆"，不动光环结构。

## 诊断（`docs/p1-merc.md`）

85 级、地狱档，以 A2 沙漠佣兵为基准：

| | A3 铁狼 | A2 沙漠 | A5 野蛮人 |
|---|---:|---:|---:|
| 85 级 HP | **1025** | 1630 | 1430 |
| 相对 A2 | **−37%** | — | −12% |
| 雇价 | **21000 / 27000 / 21000** | 15000 | **32000** |
| 相对 A2 雇价 | +40% | — | **+113%** |
| 光环 | 无 | **有**（力量 / 神圣冰冻 / 荆棘） | 无 |

A3 的问题不是"打不动"——它真正的输出是法术（火球 23 级约 500/发），
问题是**比 A2 少 37% 的血、还没有光环帮它扛，却要贵 40%**，一碰就倒。
A5 只差 12% 的血，问题纯粹是 32000 的雇价。

## 三个不能碰的东西

1. **不给 A3 / A5 加光环**：A2 强的根源是"只有它有光环"，
   给别的佣兵加就是造第二个 A2，职业差异会消失。
2. **不动 A3 的法术等级**：它不缺伤害，提等级只会变成"一碰就倒但打得更痛"。
3. **不管 A1 罗格**：她的问题（物理弓弱）在 `p2_skills.py` 里修，
   而且佣兵用的是同一套武器与技能表。

## `hireling.txt` 的坑

每行是「佣兵 × 难度 × 子类型」，A3 有 3 个子类型（冰冻/火焰/闪电），
所以必须用 `where_cols([("Hireling", ...), ("Difficulty", "3")])` 精确到行。
"""

from tools.d2patch import eq, patch

A3 = "Eastern Sorceror"
HELL = "3"

# 说明：`hireling.txt` 同时有 Version 0（经典）和 100（资料片）两套行，
# D2 LoD 实际用的是 100 —— 所以过滤里必须带 `Version=100`，否则会连经典模式的行一起改。
#
# ① A3 地狱档 HP ×1.35：863 → 1165，每级 27 → 36
#    85 级 HP 1025 → 1381（= A2 的 85%，仍然更容易死，只是不那么容易）
#    ndigits=0 必须写：HP 是整数列，1165.05 这种值 D2 解析不了
_a3 = patch(
    "hireling.txt",
    why="B1 A3 铁狼地狱档 HP ×1.35（1025 → 1381 @85，= A2 的 85%）",
).where_cols([("Hireling", eq(A3)), ("Version", eq("100")), ("Difficulty", eq(HELL))])
_a3.mul("HP", 1.35, ndigits=0)
_a3.mul("HP/Lvl", 1.35, ndigits=0)

# ② A3 雇价统一到 12000（原来三档 21000 / 27000 / 21000，比 A2 的 15000 还贵）
patch(
    "hireling.txt",
    why="B1b A3 铁狼雇价统一 12000（原 21000/27000/21000，比 A2 贵 40%）",
).where_cols([("Hireling", eq(A3)), ("Version", eq("100")), ("Difficulty", eq(HELL))]).set("Gold", 12000)

# ③ A5 野蛮人只调价 32000 → 15000（和 A2 齐平）。
#    它只差 A2 12% 的血，不该贵一倍多；**不给光环**，否则是第二个 A2。
patch(
    "hireling.txt",
    why="B2 A5 野蛮人雇价 32000→15000（血只差 A2 12%，却贵 113%）；不加光环",
).where_cols([("Hireling", eq("Barbarian")), ("Version", eq("100")),
                ("Difficulty", eq(HELL))]).set("Gold", 15000)
