"""P3 · 符文之语层：把「信念」拆成三档，补上噩梦→地狱之间的空档。

## 问题（有数字）

全游戏只有三个技能能降敌人抗性：冰掌握 −115、信念 −125、降抗诅咒 −70。
德鲁伊 / 刺客 / 亚马逊**一个都没有**，所以它们的元素线在地狱里天然冷门。
按 126 个区域的平均环境系数：

| | 系数 | 相对冰法 |
|---|---:|---:|
| 无降抗职业（裸装） | 0.61 | 45% |
| + 元素穿透 craft（−20） | 0.88 | 64% |
| **光辉（信念 L3）+ craft** | **1.23** | **89%** |
| 无限（信念 L12） | — | 饱和 |

原版给无降抗职业的答案本来是**佣兵带无限（信念 L12）**，但那是终局。
中间层（噩梦后期 → 地狱前期）是空的 —— 这里补的就是这一层。

## 动哪个、为什么是它

**`Radiance`（光辉，req 27，3 孔头盔，Nef + Sol + Ith）**

它现在是一条"光影"，6 条属性里第一条是 **`light` +5（光环半径）** —— 纯废物。
所以这次是**把一条废物属性换成功能属性**，而不是给装备加东西：

| 字段 | 前 | 后 |
|---|---|---|
| `T1Code1` | `light` | **`aura`** |
| `T1Param1` | （空） | **`Conviction`** |
| `T1Min1` / `T1Max1` | 5 / 5 | **3 / 3** |

- 头盔位置对佣兵最友好（不占玩家的核心槽），`Radiance` 本身也没人用
- 只改 `Runes.txt` 一行，**不需要动 Big5 字符串表**（名字沿用）
- 写法照抄 `Infinity`：`aura` + `param=Conviction` + min/max=等级

## 必须知道的三件事

1. **信念对免疫怪只按 1/5 生效**：−40 对免疫怪只有 −8，**破不了大部分免疫**。
   它解决的是"高抗怪打不快"，不是"打不动"。
2. **玩家自己也能戴**：任何职业戴上都能获得信念 L3。这会部分稀释圣骑士的信念，
   但无限早就稀释过了，而且骑士自己点满能到 −125。
3. **信念只管火/冰/电**，毒系吃不到（毒系已经靠降抗诅咒）。

## 回滚

把上面 4 个字段改回 `light` / 空 / 5 / 5，重跑 `tools.all` 即可。
如果游戏里觉得太强（噩梦全无压力），把 3 改成 **2**（−35）。
"""

from tools.d2patch import eq, matches, patch

_r = patch(
    "runes.txt",
    why="P3 中间层降抗：Radiance 的『光环半径 +5』换成『信念 L3（−40%）』"
        "（补噩梦→地狱之间的降抗空档，见 docs/p3-runes-plan.md）",
).where("Rune Name", matches(r"^Radiance$"))
_r.set("T1Code1", "aura")
_r.set("T1Param1", "Conviction")
_r.set("T1Min1", 3)
_r.set("T1Max1", 3)


# ------------------------------------------------------------------ 毒液 Venom
# 用户/社区名单里"定位尴尬"的典型：Tal + Dol + Mal（成本 97），
# 但只有 2 条强属性：一点点毒伤 + 7% 吸蓝 + 两个充能技能（凑数的）。
#
# 毒系真正缺的是**一把终局武器**（死亡之网是暗金、极稀有）。
# 但直接加"毒穿透 + 毒伤%"会立刻超过死亡之网（算过：任何组合都到 1.65+，DW 只有 1.55），
# 那是造新 BiS，违反 E2。
#
# 所以走**时间**而不是数值：
#   ① 把两个凑数的 `charged` 换成 `pierce-pois` 15~20（低于死亡之网的 40~50）
#   ② 关键的一条：`pois-len` **-50 帧**（-2 秒）—— 毒总量不变，但更快跳完 = DPS 更高
#      `pois-len` 是帧数：原版 `Hellplague` 是 +150（6 秒）、`Rakescar` +75（3 秒），
#      而 Venom 自己的 `dmg-pois` 持续是 175 帧（7 秒）→ 减到 125 帧（5 秒）
#
# 验收：毒死灵配降抗诅咒(-70) + 这把武器(-20) → 环境系数 1.375，**低于死亡之网的 1.55**。
# 身份因此是"让毒从慢热变能打"，而不是"比死亡之网更强"。
_v = patch(
    "runes.txt",
    why="P3 毒液重做：两个凑数充能 → pierce-pois 15~20 + pois-len -50 帧"
        "（毒更快跳完，总量不变；不超死亡之网）",
).where("Rune Name", matches(r"^Venom$"))
_v.set("T1Code3", "pierce-pois")
_v.set("T1Param3", "")
_v.set("T1Min3", 15)
_v.set("T1Max3", 20)
_v.set("T1Code4", "pois-len")
_v.set("T1Param4", "")
_v.set("T1Min4", -50)
_v.set("T1Max4", -50)


# ------------------------------------------------------------------ 天底 Nadir
# 0 条强属性，而且**带两条纯负面**：`light -3`（看得更暗）、`gold% -33`（捡钱更少）。
# 一个 req 13 的早期头盔，带负面属性没有任何道理 —— 换成早期最缺的两样：法力与回蓝。
# 身份：**法系开荒头盔**（其它三条 +50% 防御 / +10 防御 / +5 力量 / 暗影斗篷充能 保留不动）。
_n = patch(
    "runes.txt",
    why="P3 天底重做：去掉两条负面（light -3 / gold -33），换成 +法力 与 回蓝",
).where("Rune Name", matches(r"^Nadir$"))
_n.set("T1Code3", "mana")
_n.set("T1Param3", "")
_n.set("T1Min3", 20)
_n.set("T1Max3", 20)
_n.set("T1Code5", "regen-mana")
_n.set("T1Param5", "")
_n.set("T1Min5", 25)
_n.set("T1Max5", 25)
